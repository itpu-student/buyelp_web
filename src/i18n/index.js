import { reactive } from "vue"

export const i18nState = reactive({
  locale: localStorage.getItem("s101__lang") || "en",
})

export function setLocale(lang) {
  i18nState.locale = lang
  localStorage.setItem("s101__lang", lang)
}

export function t(keyPath, vars) {
  const keys = keyPath.split(".")
  let val = messages[i18nState.locale]
  for (const k of keys) {
    if (!val) return keyPath
    val = val[k]
  }
  let result = val || keyPath
  if (vars && typeof result === 'string') {
    for (const [k, v] of Object.entries(vars)) {
      result = result.replace(`{${k}}`, v)
    }
  }
  return result
}
